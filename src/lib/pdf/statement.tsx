import { Document, Page, StyleSheet, Text, View, renderToBuffer } from "@react-pdf/renderer";
import { formatPula } from "@/lib/money";

export interface StatementData {
  business: { name: string; address: string | null; phone: string | null; vat_number: string | null; invoice_footer: string | null };
  customer: { name: string; phone: string | null; company: string | null };
  generatedAt: string;
  /** Oldest first. */
  rows: { at: string; kind: "invoice" | "payment"; ref: string; detail: string; debit: number; credit: number }[];
}

const GREY = "#6b7280";
const s = StyleSheet.create({
  page: { padding: 40, fontSize: 10, fontFamily: "Helvetica", color: "#111827" },
  header: { flexDirection: "row", justifyContent: "space-between", marginBottom: 20 },
  shop: { fontSize: 16, fontFamily: "Helvetica-Bold" },
  muted: { color: GREY },
  title: { fontSize: 20, fontFamily: "Helvetica-Bold", color: "#047857", textAlign: "right" },
  th: { flexDirection: "row", borderBottomWidth: 1, borderColor: "#e5e7eb", paddingVertical: 6, color: GREY, fontSize: 8 },
  tr: { flexDirection: "row", borderBottomWidth: 1, borderColor: "#f3f4f6", paddingVertical: 5 },
  cDate: { width: 70 },
  cRef: { width: 80 },
  cDetail: { flexGrow: 1, flexBasis: 0 },
  cMoney: { width: 80, textAlign: "right" },
  due: { marginTop: 14, marginLeft: "auto", width: 240, flexDirection: "row", justifyContent: "space-between", borderTopWidth: 1, borderColor: "#111827", paddingTop: 6, fontFamily: "Helvetica-Bold", fontSize: 12 },
  footer: { position: "absolute", left: 40, right: 40, bottom: 30, fontSize: 8, color: GREY, borderTopWidth: 1, borderColor: "#e5e7eb", paddingTop: 8 },
});

const day = (iso: string) =>
  new Date(iso).toLocaleDateString("en-GB", { timeZone: "Africa/Gaborone", day: "2-digit", month: "short", year: "numeric" });

function StatementDocument({ data }: { data: StatementData }) {
  let running = 0;
  const rows = data.rows.map((r) => {
    running += r.debit - r.credit;
    return { ...r, balance: running };
  });
  return (
    <Document title={`Statement ${data.customer.name}`} author="Morekisi">
      <Page size="A4" style={s.page}>
        <View style={s.header}>
          <View>
            <Text style={s.shop}>{data.business.name}</Text>
            {data.business.address && <Text style={s.muted}>{data.business.address}</Text>}
            {data.business.phone && <Text style={s.muted}>{data.business.phone}</Text>}
            {data.business.vat_number && <Text style={s.muted}>VAT No: {data.business.vat_number}</Text>}
          </View>
          <View>
            <Text style={s.title}>STATEMENT</Text>
            <Text style={[s.muted, { textAlign: "right" }]}>{day(data.generatedAt)}</Text>
          </View>
        </View>

        <Text style={[s.muted, { fontSize: 8 }]}>ACCOUNT</Text>
        <Text>{data.customer.name}</Text>
        {data.customer.company && <Text style={s.muted}>{data.customer.company}</Text>}
        {data.customer.phone && <Text style={s.muted}>{data.customer.phone}</Text>}

        <View style={{ marginTop: 18 }}>
          <View style={s.th}>
            <Text style={s.cDate}>DATE</Text>
            <Text style={s.cRef}>REFERENCE</Text>
            <Text style={s.cDetail}>DETAIL</Text>
            <Text style={s.cMoney}>CHARGED</Text>
            <Text style={s.cMoney}>PAID</Text>
            <Text style={s.cMoney}>BALANCE</Text>
          </View>
          {rows.length === 0 && <Text style={[s.muted, { paddingVertical: 8 }]}>No account activity.</Text>}
          {rows.map((r, i) => (
            <View key={i} style={s.tr} wrap={false}>
              <Text style={s.cDate}>{day(r.at)}</Text>
              <Text style={s.cRef}>{r.ref}</Text>
              <Text style={s.cDetail}>{r.kind === "invoice" ? "Invoice" : `Payment (${r.detail})`}</Text>
              <Text style={s.cMoney}>{r.debit ? formatPula(r.debit) : ""}</Text>
              <Text style={s.cMoney}>{r.credit ? formatPula(r.credit) : ""}</Text>
              <Text style={s.cMoney}>{formatPula(r.balance)}</Text>
            </View>
          ))}
        </View>

        <View style={s.due}>
          <Text>{running >= 0 ? "Amount due" : "In credit"}</Text>
          <Text>{formatPula(Math.abs(running))}</Text>
        </View>

        <View style={s.footer} fixed>
          {data.business.invoice_footer && <Text style={{ marginBottom: 4, color: "#374151" }}>{data.business.invoice_footer}</Text>}
          <Text>Only sales on account and payments are shown. · Generated by Morekisi</Text>
        </View>
      </Page>
    </Document>
  );
}

export async function renderStatementPdf(data: StatementData): Promise<Buffer> {
  return renderToBuffer(<StatementDocument data={data} />);
}
